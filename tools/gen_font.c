// Generates overlay/font_data.h: monospace ASCII (32..126) alpha bitmaps at a
// few pixel sizes, rasterized from a TTF with stb_truetype. Build-time tool;
// the generated header is checked in.
//
//   cc -O2 -I<dir with stb_truetype.h> tools/gen_font.c -lm -o gen_font
//   ./gen_font DejaVuSansMono.ttf 22 34 > overlay/font_data.h
#define STB_TRUETYPE_IMPLEMENTATION
#include "stb_truetype.h"

#include <stdio.h>
#include <stdlib.h>

static unsigned char* ReadFile(const char* path) {
  FILE* f = fopen(path, "rb");
  if (!f) return NULL;
  fseek(f, 0, SEEK_END);
  long n = ftell(f);
  fseek(f, 0, SEEK_SET);
  unsigned char* buf = malloc(n);
  if (fread(buf, 1, n, f) != (size_t)n) {
    fclose(f);
    return NULL;
  }
  fclose(f);
  return buf;
}

int main(int argc, char** argv) {
  if (argc < 3) {
    fprintf(stderr, "usage: %s font.ttf px [px...]\n", argv[0]);
    return 1;
  }
  unsigned char* ttf = ReadFile(argv[1]);
  stbtt_fontinfo font;
  if (!ttf || !stbtt_InitFont(&font, ttf, stbtt_GetFontOffsetForIndex(ttf, 0))) {
    fprintf(stderr, "cannot load %s\n", argv[1]);
    return 1;
  }
  printf("// Generated by tools/gen_font.c from DejaVu Sans Mono (Bitstream Vera\n"
         "// derived license, see THIRD_PARTY.md). Do not edit.\n"
         "#pragma once\n#include <cstdint>\n\nnamespace recline_font {\n\n"
         "struct FontFace {\n  int px, cellW, cellH, ascent;\n  const uint8_t* alpha;  "
         "// 95 cells (ASCII 32..126), cellW*cellH each\n};\n\n");
  int nfaces = argc - 2;
  for (int fi = 0; fi < nfaces; ++fi) {
    int px = atoi(argv[2 + fi]);
    float scale = stbtt_ScaleForPixelHeight(&font, (float)px);
    int asc, desc, gap, adv, lsb;
    stbtt_GetFontVMetrics(&font, &asc, &desc, &gap);
    stbtt_GetCodepointHMetrics(&font, 'M', &adv, &lsb);
    int cellW = (int)(adv * scale + 0.5f);
    int ascent = (int)(asc * scale + 0.5f);
    int cellH = ascent + (int)(-desc * scale + 0.5f) + 1;
    unsigned char* cell = calloc(cellW * cellH, 1);
    printf("static const uint8_t kAlpha%d[] = {\n", px);
    for (int ch = 32; ch < 127; ++ch) {
      memset(cell, 0, cellW * cellH);
      int x0, y0, x1, y1;
      stbtt_GetCodepointBitmapBox(&font, ch, scale, scale, &x0, &y0, &x1, &y1);
      int gw = x1 - x0, gh = y1 - y0;
      if (gw > 0 && gh > 0) {
        unsigned char* g = calloc(gw * gh, 1);
        stbtt_MakeCodepointBitmap(&font, g, gw, gh, gw, scale, scale, ch);
        int ox = x0;  // lsb applied by x0
        int oy = ascent + y0;
        for (int y = 0; y < gh; ++y)
          for (int x = 0; x < gw; ++x) {
            int cx = ox + x, cy = oy + y;
            if (cx >= 0 && cx < cellW && cy >= 0 && cy < cellH) cell[cy * cellW + cx] = g[y * gw + x];
          }
        free(g);
      }
      printf("  // '%c'\n ", ch == '\\' ? '/' : ch);
      for (int i = 0; i < cellW * cellH; ++i) {
        printf(" %d,", cell[i]);
        if (i % 32 == 31) printf("\n ");
      }
      printf("\n");
    }
    printf("};\n");
    printf("static const FontFace kFace%d = {%d, %d, %d, %d, kAlpha%d};\n\n", px, px, cellW, cellH,
           ascent, px);
    free(cell);
  }
  printf("}  // namespace recline_font\n");
  return 0;
}
